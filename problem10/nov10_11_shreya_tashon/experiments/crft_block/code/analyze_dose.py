"""Dose-test analysis (runs locally on the per-pair ruler files; no GPU).
Gap closed = (mean_broken - mean_arm) / (mean_broken - mean_normal) on the 705 held-out pairs; paired bootstrap over pairs
(B=2000, same resampled pairs for every arm and the references). The bootstrap covers QUESTION sampling noise only.
Pre-registered rule (see PREREGISTRATION.md): circuit beats random at a checkpoint iff circuit point > max(random points)
AND circuit CI-low > max(random CI-highs).   Usage: python analyze_dose.py DIR [DIR ...] --out OUT.md"""
import argparse, glob, json, math, os, re
import numpy as np

ap = argparse.ArgumentParser(); ap.add_argument("dirs", nargs="+"); ap.add_argument("--out", required=True)
a = ap.parse_args()
STEPS = [10, 25, 50, 100]; B = 2000
R, M = {}, {}
for d in a.dirs:
    for f in glob.glob(os.path.join(d, "ruler_*.json")):
        k = os.path.basename(f)[6:-5]
        R.setdefault(k, np.array(json.load(open(f))))
    for f in glob.glob(os.path.join(d, "medqa_*.json")):
        M.setdefault(os.path.basename(f)[6:-5], np.array(json.load(open(f))))
N = len(R["normal"]); assert N == 705 and len(R["broken"]) == N
rng = np.random.default_rng(0); IDX = rng.integers(0, N, (B, N))
def bmean(x): return x[IDX].mean(1)
bB, nB = bmean(R["broken"]), bmean(R["normal"]); b0, n0 = R["broken"].mean(), R["normal"].mean()
def gap(x): return 100 * (b0 - x.mean()) / (b0 - n0)
def gap_boot(x): return 100 * (bB - bmean(x)) / (bB - nB)
def ci(v): return float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5))
cells = {}
for k, x in R.items():
    m = re.match(r"(.+)_step(\d+)$", k)
    if m: cells[(m.group(1), int(m.group(2)))] = dict(p=gap(x), ci=ci(gap_boot(x)), boot=gap_boot(x), ruler=x.mean())
arms = sorted({k[0] for k in cells}, key=lambda s: (["circuit_mlp", "random_mlp_s1", "random_mlp_s2", "random_mlp_s3", "random_mlp_s0", "circuit_mlp_ts1",
        "circuit_attn", "random_attn_s1", "random_attn_s2", "circuit_attn_ts1", "full"].index(s) if s in
        ["circuit_mlp", "random_mlp_s1", "random_mlp_s2", "random_mlp_s3", "random_mlp_s0", "circuit_mlp_ts1", "circuit_attn", "random_attn_s1",
         "random_attn_s2", "circuit_attn_ts1", "full"] else 99, s))
L = []; P = L.append
P(f"# Dose test results (auto-generated by analyze_dose.py)\n\nReferences on the 705 held-out pairs: ruler normal {n0:.4f}, broken {b0:.4f} "
  f"(old CRFT run: -0.9149 / -0.1571). Gap closed in % (95% bootstrap CI over pairs).\n")
P("## Gap closed (%) per arm x checkpoint\n"); P("| arm | " + " | ".join(f"step {s}" for s in STEPS) + " |"); P("|---|" + "---|" * len(STEPS))
for ar in arms:
    P(f"| {ar} | " + " | ".join(f"{cells[(ar, s)]['p']:.1f} ({cells[(ar, s)]['ci'][0]:.1f} to {cells[(ar, s)]['ci'][1]:.1f})" if (ar, s) in cells else "-" for s in STEPS) + " |")
# ---- pre-registered comparison
PREREG = {"mlp": ("circuit_mlp", ["random_mlp_s1", "random_mlp_s2", "random_mlp_s3"]), "attn": ("circuit_attn", ["random_attn_s1", "random_attn_s2"])}
P("\n## Pre-registered test: circuit beats random (point > max random point AND CI-low > max random CI-high)\n")
P("| family | step | circuit | best random (arm) | max random CI-high | beats? | paired diff circuit - best random (95%) |"); P("|---|---|---|---|---|---|---|")
verdict = {}
for fam, (c, rs) in PREREG.items():
    for s in STEPS:
        if (c, s) not in cells or not all((r, s) in cells for r in rs): continue
        cc = cells[(c, s)]; best = max(rs, key=lambda r: cells[(r, s)]["p"]); mx_hi = max(cells[(r, s)]["ci"][1] for r in rs)
        win = cc["p"] > cells[best, s]["p"] and cc["ci"][0] > mx_hi; verdict[(fam, s)] = win
        d = cc["boot"] - cells[(best, s)]["boot"]; lo, hi = ci(d)
        P(f"| {fam} | {s} | {cc['p']:.1f} ({cc['ci'][0]:.1f}-{cc['ci'][1]:.1f}) | {cells[(best, s)]['p']:.1f} ({best}) | {mx_hi:.1f} | **{'YES' if win else 'no'}** | {cc['p'] - cells[(best, s)]['p']:+.1f} ({lo:+.1f} to {hi:+.1f}) |")
P("\n(The paired-difference column is supplementary, not the pre-registered rule. All CIs cover question noise only; the spread between random arms covers floor choice.)\n")
# ---- extras / sensitivity
P("## Extras (not part of the pre-registered rule)\n")
if all(("random_mlp_s0", s) in cells for s in STEPS):
    P("Old seed-0 random draw added to the MLP random set:\n"); 
    for s in STEPS:
        c = cells[("circuit_mlp", s)]; rs = ["random_mlp_s1", "random_mlp_s2", "random_mlp_s3", "random_mlp_s0"]
        P(f"- step {s}: circuit {c['p']:.1f} vs max random {max(cells[(r, s)]['p'] for r in rs):.1f}; beats (rule)? {c['p'] > max(cells[(r, s)]['p'] for r in rs) and c['ci'][0] > max(cells[(r, s)]['ci'][1] for r in rs)}")
for fam, ts in (("mlp", "circuit_mlp_ts1"), ("attn", "circuit_attn_ts1")):
    if all((ts, s) in cells for s in STEPS):
        P(f"\nTraining-seed control, {fam}: same circuit floors, training seed 1 (different data order and LoRA init) vs seed 0:\n")
        for s in STEPS:
            c0, c1 = cells[(f"circuit_{fam}", s)], cells[(ts, s)]
            P(f"- step {s}: seed 0 {c0['p']:.1f} vs seed 1 {c1['p']:.1f} (difference {c1['p'] - c0['p']:+.1f} points)")
# ---- steps to 30%
def cross(ys, thr=30.0):
    xs = [0] + STEPS
    for i in range(1, len(xs)):
        if ys[i] >= thr: return xs[i - 1] + (thr - ys[i - 1]) * (xs[i] - xs[i - 1]) / (ys[i] - ys[i - 1]) if ys[i] != ys[i - 1] else xs[i]
    return math.inf
P("\n## Steps to reach 30% of the gap (linear interpolation between checkpoints, 0% at step 0; bootstrap 95% in brackets)\n")
P("| arm | first checkpoint >= 30% | interpolated steps | bootstrap 95% |"); P("|---|---|---|---|")
for ar in arms:
    if not all((ar, s) in cells for s in STEPS): continue
    ys = [0.0] + [cells[(ar, s)]["p"] for s in STEPS]; c = cross(ys)
    bs = [cross([0.0] + [cells[(ar, s)]["boot"][i] for s in STEPS]) for i in range(B)]
    lo, hi = ci([min(x, 1e9) for x in bs]); fmt = lambda v: ">100" if v > 100 else f"{v:.0f}"
    first = next((s for s in STEPS if cells[(ar, s)]["p"] >= 30), None)
    P(f"| {ar} | {first if first else 'none by 100'} | {'>100' if math.isinf(c) else f'{c:.0f}'} | {fmt(lo)} to {fmt(hi)} |")
# ---- MedQA
def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n; c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d; return 100 * p, 100 * (c - h), 100 * (c + h)
def mcnemar(x, y):
    b, c = int(((x == 1) & (y == 0)).sum()), int(((x == 0) & (y == 1)).sum()); n = b + c
    if n == 0: return 1.0, b, c
    k = min(b, c); p = min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n); return p, b, c
P("\n## MedQA (1,142 questions, greedy 8 tokens) at step 100\n"); P("| model | correct | % (Wilson 95%) | McNemar p vs broken (arm-only right / broken-only right) |"); P("|---|---|---|---|")
if "broken" in M:
    k = int(M["broken"].sum()); w = wilson(k, len(M["broken"])); P(f"| broken | {k} | {w[0]:.1f} ({w[1]:.1f}-{w[2]:.1f}) | - |")
for ar in arms:
    key = f"{ar}_step100"
    if key in M and "broken" in M:
        k = int(M[key].sum()); w = wilson(k, len(M[key])); p, bb, cc = mcnemar(M[key], M["broken"])
        P(f"| {ar} | {k} | {w[0]:.1f} ({w[1]:.1f}-{w[2]:.1f}) | {p:.2f} ({bb}/{cc}) |")
open(a.out, "w").write("\n".join(L) + "\n"); print("\n".join(L))
json.dump({"verdict": {f"{f}_{s}": bool(v) for (f, s), v in verdict.items()},
           "cells": {f"{k[0]}_step{k[1]}": {"gap_closed": v["p"], "ci": v["ci"], "ruler_mean": float(v["ruler"])} for k, v in cells.items()}},
          open(a.out.replace(".md", ".json"), "w"), indent=1)
