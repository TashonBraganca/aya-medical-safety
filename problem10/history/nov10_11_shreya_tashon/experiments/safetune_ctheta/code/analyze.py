def wilson(k, n, z=1.96):
    p = k / n; dd = 1 + z * z / n; cc = (p + z * z / (2 * n)) / dd; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / dd
    return round(100 * p, 1), round(100 * (cc - h), 1), round(100 * (cc + h), 1)
def mcnemar(b, cc):
    n = b + cc; return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, k) for k in range(min(b, cc) + 1)) / 2 ** n)
